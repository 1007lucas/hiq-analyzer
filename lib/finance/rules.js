export function ruleCategory(domain, tx) {
  const d = tx.desc || '';
  if (domain === 'personal') {
    if (tx.amount > 0) {
      if (/이체|송금|토스|카카오페이|ATM|충전/i.test(d) && !PERSONAL_INCOME_RULES.test(d)) return '이체·송금';
      return '수입';
    }
    for (const [cat, re] of PERSONAL_RULES) if (re.test(d)) return cat;
    return null;
  }
  // academy
  if (tx.amount > 0) {
    for (const [cat, re] of ACADEMY_INCOME_RULES) if (re.test(d)) return cat;
    if (/대표자|사업주|가수금|자기앞|내부|예금\s*해지|적금\s*해지|ATM/i.test(d)) return '이체·내부거래';
    return null; // 보호자 이름만 있는 입금(타행이체 등) → AI 판단
  }
  for (const [cat, re] of ACADEMY_RULES) if (re.test(d)) return cat;
  return null;
}

export function defaultCategory(domain, tx) {
  if (domain === 'personal') return tx.amount > 0 ? '수입' : '기타';
  return tx.amount > 0 ? '수강료 수입' : '기타 지출';
}

// 설명 정규화 (가맹점 기억·반복결제 탐지에 공용)
export function normalizeDesc(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/\(주\)|주식회사|\(유\)|유한회사|결제|승인|자동이체|자동결제|정기결제|월정액/g, '')
    .replace(/[0-9]/g, '')
    .replace(/[^\p{L}]/gu, '')
    .slice(0, 24);
}
